import { test, expect } from '@playwright/test';

const BASE_URL = process.env.APP_URL || 'http://localhost:3000';

test.describe('Homingo Tutor Track C3 4-Pillar Verification', () => {
  test.setTimeout(180000);

  test('Pillar A & B: Site Loads, Onboards Learner, and Starts Diagnostic', async ({ page }) => {
    const pageErrors: string[] = [];
    page.on('pageerror', (err) => pageErrors.push(err.message));

    // 1. Check Homepage availability
    const response = await page.goto(BASE_URL);
    expect(response?.status()).toBe(200);

    // 2. Click Start Learning or navigate to onboard
    await page.goto(`${BASE_URL}/onboard`);
    await expect(page.locator('text=Customize Your Learning Session')).toBeVisible();

    // 3. Test Language Selection (Pillar B: Hinglish)
    const hinglishBtn = page.locator('button:has-text("Hinglish")');
    await expect(hinglishBtn).toBeVisible();
    await hinglishBtn.click();

    // 4. Select Chapter
    const quadBtn = page.locator('button:has-text("Quadratic Equations")');
    await expect(quadBtn).toBeVisible();
    await quadBtn.click();

    // 5. Submit Onboard form
    const startBtn = page.locator('button:has-text("Begin Diagnostic Assessment")');
    await expect(startBtn).toBeVisible();
    await startBtn.click();

    // 6. Verify Diagnostic Exam Loads (Pillar A)
    await expect(page).toHaveURL(/.*diagnostic.*/, { timeout: 35000 });
    await expect(page.locator('text=Diagnostic Question')).toBeVisible({ timeout: 35000 });

    // Verify no runtime crashes
    expect(pageErrors.filter(e => !e.includes('ResizeObserver'))).toEqual([]);
  });

  test('Pillar C & D: Instant Demo Mode, Socratic Tutor & Proof-of-Learning Report', async ({ page }) => {
    const pageErrors: string[] = [];
    page.on('pageerror', (err) => pageErrors.push(err.message));

    // 1. Launch Instant Demo Mode from homepage
    await page.goto(BASE_URL);
    const demoBtn = page.locator('button:has-text("Instant Demo Mode")');
    await expect(demoBtn).toBeVisible();
    await demoBtn.click();

    // 2. Verify navigation to /diagnostic
    await expect(page).toHaveURL(/.*diagnostic.*/, { timeout: 35000 });
    await expect(page.locator('text=Diagnostic Question')).toBeVisible({ timeout: 35000 });

    // 3. Answer diagnostic questions until baseline is complete
    for (let i = 0; i < 8; i++) {
      if (await page.locator('text=Your Baseline Mastery Map').isVisible().catch(() => false)) break;

      const optionB = page.locator('button[data-option-id="B"]');
      const submitBtn = page.locator('button:has-text("Submit Answer")');
      if (await optionB.isVisible({ timeout: 4000 }).catch(() => false)) {
        await optionB.click();
        await page.waitForTimeout(400);
        await expect(submitBtn).toBeEnabled({ timeout: 5000 });
        await submitBtn.click();
        await page.waitForTimeout(3000);
      }
    }

    // Wait for baseline score card to appear
    await expect(page.locator('text=Your Baseline Mastery Map')).toBeVisible({ timeout: 35000 });

    // 4. Navigate into Socratic Tutoring (Pillar C)
    const enterTutorBtn = page.locator('button:has-text("Start Socratic Tutoring Session")');
    await enterTutorBtn.click();

    await expect(page).toHaveURL(/.*tutor.*/, { timeout: 15000 });
    await expect(page.locator('text=Homingo Tutor')).toBeVisible();

    // 5. Interact with Socratic Tutor (Hint Ladder)
    const hintBtn = page.locator('button:has-text("Hint")');
    await expect(hintBtn).toBeVisible();
    await hintBtn.click();

    // Verify AI response arrives
    await page.waitForTimeout(4000);
    const messages = page.locator('.max-w-\\[85\\%\\]');
    await expect(messages.first()).toBeVisible();

    // 6. Verify Retest and Proof of Learning Report (Pillar D)
    const retestNavBtn = page.locator('button:has-text("Take Retest")');
    await expect(retestNavBtn).toBeVisible();
    await retestNavBtn.click();

    await expect(page).toHaveURL(/.*retest.*/, { timeout: 35000 });

    // Wait for fresh retest questions to be generated by Gemini
    await expect(page.locator('button[data-option-id="A"]')).toBeVisible({ timeout: 45000 });

    // Answer retest questions until report page is reached
    for (let i = 0; i < 6; i++) {
      if (page.url().includes('/report/')) break;

      const submitRetestBtn = page.locator('button:has-text("Submit Retest Answer")');
      const isVisible = await submitRetestBtn.isVisible({ timeout: 5000 }).catch(() => false);
      if (!isVisible) break;

      const optionA = page.locator('button[data-option-id="A"]').first();
      if (await optionA.isVisible({ timeout: 4000 }).catch(() => false)) {
        await optionA.click();
        await page.waitForTimeout(500);

        if (await submitRetestBtn.isEnabled({ timeout: 3000 }).catch(() => false)) {
          await submitRetestBtn.click();
          await page.waitForTimeout(5000);
        }
      }
    }

    // 7. Verify Proof of Learning Report arrives (Pillar D)
    await expect(page).toHaveURL(/.*report.*/, { timeout: 60000 });
    await expect(page.locator('text=CBSE Math')).toBeVisible({ timeout: 35000 });
    await expect(page.locator('text=Total Learning Gain')).toBeVisible();

    // Verify no runtime crashes
    expect(pageErrors.filter(e => !e.includes('ResizeObserver'))).toEqual([]);
  });
});
